# 系统瘦身里“不用重编镜像”的部分：容器启动前改系统盘里的 init.kindle.rc 和 build.prop（和 heap_fix 一样，系统盘对宿主可写）。
# 设置 SLIM=1（默认）打开，SLIM=0 把这两处改动撤掉。每处改动都包在 ">>> vd-slim" / "<<< vd-slim" 标记之间，
# 内容没变就不写盘。实测和每一项的依据见 docs/slim-android.md。
#
# init（init.kindle.rc 先于 /system/etc/init/*.rc 解析，同名服务先定义的生效，所以在这里重定义成 disabled 就不会被 class main 拉起）：
#   mediacodec / mediadrm / mediaextractor：mediaserver（media.player）本来就是 disabled，这三个没有它什么也做不了，白占 3 个进程约 5.5 MB，
#       还在开机最挤的时候和 zygote 抢两个核。audioserver 必须留（AudioService 等 media.audio_policy）。
#   bootanim：SurfaceFlinger 每次开机都 ctl.start 它，bootanimation 要装载 libandroid_runtime 一大串库才发现
#       debug.sf.nobootanimation=1 然后退出。换成 /system/bin/true。
# 属性（SystemServer.java 7.1.1 里读的 config.disable_*，只列对阅读器无害的）：
#   config.disable_bluetooth    没装 Bluetooth.apk 的镜像上：不起 BluetoothService（否则每次开机 "Auto-enabling Bluetooth" 再绑定失败）
#   config.disable_rtt          Wi-Fi RTT 测距服务
#   config.disable_mediaproj    录屏 / 投屏（MediaProjection）
#   config.disable_serial       串口服务
#   config.disable_samplingprof 采样分析器
#   config.disable_networktime  NTP 校时（时间归 Kindle 管，容器和 Kindle 共用时钟）
#   config.disable_otadexopt    A/B OTA 的 dexopt 服务
#   ro.zygote.disable_gl_preload  zygote 不预加载 EGL（应用全部软件绘制，用到 GL 的进程自己初始化）
# 故意不用的：config.disable_noncore（连剪贴板、DevicePolicy、AppWidget、输入法依赖的 TextServices 一起砍，应用拿到 null 服务会崩）、
#   config.disable_location（LocationManager 拿到空 binder，应用一调就 NPE）、config.disable_network（网络）、config.disable_storage（/sdcard）、
#   config.disable_systemui / searchmanager / trustmanager / textservices（省不了多少，换来 getSystemService 返回 null 的风险）。
SLIM_B='# >>> vd-slim (generated by boot/lib/slim.sh, do not edit between the markers)'
SLIM_E='# <<< vd-slim'

slim_rc_block() {
    cat <<'RC'
service mediacodec /system/bin/mediacodec
    class main
    user mediacodec
    group camera drmrpc mediadrm
    disabled

service mediadrm /system/bin/mediadrmserver
    class main
    user media
    group mediadrm drmrpc
    disabled

service mediaextractor /system/bin/mediaextractor
    class main
    user mediaex
    group drmrpc mediadrm
    disabled

service bootanim /system/bin/true
    class core
    user graphics
    group graphics
    disabled
    oneshot
RC
}

slim_prop_block() {
    echo "ro.zygote.disable_gl_preload=true"
    for k in rtt mediaproj serial samplingprof networktime otadexopt; do echo "config.disable_$k=true"; done
    # 有蓝牙应用的镜像（PW6 蓝牙版）不能关
    [ -d "$R/system/app/Bluetooth" ] || [ -d "$R/system/priv-app/Bluetooth" ] || echo "config.disable_bluetooth=true"
}

# 把 $1 里两个标记之间的内容换成 stdin（stdin 为空 = 只删掉）。内容相同不写盘。保持 644（init 拒绝组 / 其他人可写的 rc）。
slim_block_set() {
    f=$1; [ -f "$f" ] || return 0
    new=$W/slim.new.$$; cur=$W/slim.cur.$$
    cat > $new
    sed -n "/^# >>> vd-slim/,/^# <<< vd-slim/p" "$f" | sed '1d;$d' > $cur
    if cmp -s $new $cur; then rm -f $new $cur; return 1; fi
    { sed "/^# >>> vd-slim/,/^# <<< vd-slim/d" "$f"
      if [ -s $new ]; then echo "$SLIM_B"; cat $new; echo "$SLIM_E"; fi; } > "$f.vdslim" \
        && chmod 644 "$f.vdslim" && mv -f "$f.vdslim" "$f"
    rm -f $new $cur
    return 0
}

# 用不上的系统应用：从系统盘挪到 $SYS/slim-removed/（不删，SLIM=0 时挪回去）。PackageManager 每次开机都要扫描 /system 下的
# 每个包，少一个就少扫一个；它发现系统包没了会自己清掉对应的设置项。
#   CtsShimPrebuilt / CtsShimPrivPrebuilt  兼容性测试用的空壳
#   WallpaperBackup                        壁纸备份（壁纸服务已经用 overlay 关掉）
#   BackupRestoreConfirmation              adb 备份的确认界面
# 不能动的（模拟器实测：缺了 system_server 开机就崩、无限重启）：StatementService（PackageManager 要求“至少有一个 intent filter verifier”）；
#   按源码同理的：ExtServices / ExtShared（要求这两个共享库存在）、PackageInstaller（要求恰好一个安装器）；
#   DefaultContainerService（安装 APK）、DownloadProvider / MediaProvider（应用下载、媒体库）、Shell、SettingsProvider、InputDevices、webview。
SLIM_PRUNE="app/CtsShimPrebuilt priv-app/CtsShimPrivPrebuilt app/WallpaperBackup priv-app/BackupRestoreConfirmation"
slim_prune() {
    # 以前的版本挪走、现在不在名单里的：先放回去（名单只会因为“发现它其实不能动”而变短）
    for d in "$SYS"/slim-removed/app/* "$SYS"/slim-removed/priv-app/*; do
        [ -d "$d" ] || continue
        a=${d#$SYS/slim-removed/}
        case " $SLIM_PRUNE " in *" $a "*) continue ;; esac
        [ -e "$R/system/$a" ] || { mv "$d" "$R/system/$a" && t "slim: $a put back (no longer on the list)"; }
    done
    n=0
    for a in $SLIM_PRUNE; do
        [ -d "$R/system/$a" ] || continue
        mkdir -p "$SYS/slim-removed/${a%/*}" && rm -rf "$SYS/slim-removed/$a" && mv "$R/system/$a" "$SYS/slim-removed/$a" && n=$((n + 1))
    done
    [ $n -gt 0 ] && t "slim: $n unused system apps moved out of the image ($SYS/slim-removed)"
    return 0
}
slim_unprune() {
    n=0
    for d in "$SYS"/slim-removed/app/* "$SYS"/slim-removed/priv-app/*; do
        [ -d "$d" ] || continue
        a=${d#$SYS/slim-removed/}
        [ -e "$R/system/$a" ] || { mv "$d" "$R/system/$a" && n=$((n + 1)); }
    done
    [ $n -gt 0 ] && t "slim: off, $n system apps put back"
    return 0
}

slim_apply() {
    [ -f "$R/init.kindle.rc" ] && [ -f "$R/system/build.prop" ] || return 0
    if [ "${SLIM:-1}" = 1 ]; then
        # 用 slim 产品编出来的镜像（ro.vd.slim=1）自带这两处，不用再加
        if grep -q '^ro.vd.slim=1' "$R/system/build.prop"; then
            : | slim_block_set "$R/init.kindle.rc"; : | slim_block_set "$R/system/build.prop"
        else
            slim_rc_block | slim_block_set "$R/init.kindle.rc" && t "slim: init.kindle.rc updated (media helpers + bootanim off)"
            slim_prop_block | slim_block_set "$R/system/build.prop" && t "slim: build.prop updated ($(slim_prop_block | wc -l | tr -d ' ') props)"
        fi
        slim_prune
    else
        : | slim_block_set "$R/init.kindle.rc" && t "slim: off, init.kindle.rc restored"
        : | slim_block_set "$R/system/build.prop" && t "slim: off, build.prop restored"
        slim_unprune
    fi
    return 0
}

# 开机后写入 PackageManager 的状态（首次开机、升级或 SLIM 开关变化时执行，避免每次开机重复起 JVM）。
#   MediaScannerReceiver：每次开机和每次“存储已挂载”都把整个 /sdcard（含绑进来的 Kindle 书库）扫进媒体库，开机后白烧 CPU。
#       关的是这个广播接收器，MediaScannerConnection（应用主动请求扫描某个文件）走服务，不受影响。
slim_after_boot() {
    _sl=${SLIM:-1}; _sm=$SYS/data/.vd-slim-pm
    [ -z "${AB_ONCE:-}" ] && [ "$(cat "$_sm" 2>/dev/null)" = "$_sl" ] && return 0
    if [ "$_sl" = 1 ]; then
        adb_sh 'pm disable com.android.providers.media/com.android.providers.media.MediaScannerReceiver' >/dev/null 2>&1 || return 1
        t "slim: boot media scan disabled"
    else
        adb_sh 'pm enable com.android.providers.media/com.android.providers.media.MediaScannerReceiver' >/dev/null 2>&1 || return 1
        t "slim: boot media scan restored"
    fi
    echo "$_sl" > "$_sm" 2>/dev/null || true
}

# su 对应用藏起来（HIDE_SU=1，默认）。userdebug 镜像带 /system/xbin/su（AOSP 的 su 只认 root / shell，应用本来就用不了它），
# 但加固应用（爱加密 ijiami 的 libijm_linker：which su、/system/xbin/ /system/bin/ /sbin/ ... 下找 su）看见它就当成 root 设备，
# 原生壳 0.5–1.5 秒内故意 SIGSEGV 自杀，Android 无限重启它（不背单词 5.11.10，模拟器：有 su 12/12 次崩，改名后过了壳）。
# 只改名不删：/system/xbin/vdsu（同一个 inode，增量更新按内容找得到它），HIDE_SU=0 改回去。宿主自己的工具都从 nsenter 以 root 进容器，
# 不用 su；测试脚本用 vdsu。新镜像里又带了 su 时，开机前再改一次。
su_hide() {
    su_x=$R/system/xbin
    [ -d "$su_x" ] || return 0
    if [ "${HIDE_SU:-1}" = 1 ]; then
        [ -f "$su_x/su" ] || return 0
        mv -f "$su_x/su" "$su_x/vdsu" && t "su: hidden from apps (system/xbin/su -> vdsu)" || t "su: could not hide (read-only image?)"
    else
        [ -f "$su_x/vdsu" ] && [ ! -e "$su_x/su" ] && mv "$su_x/vdsu" "$su_x/su" && t "su: HIDE_SU=0, system/xbin/su put back"
    fi
    return 0
}
