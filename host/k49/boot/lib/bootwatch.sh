# 看着 Android 开机：把它自己的 boot_progress 事件换成进度条和文字；开机完成（或超时）就放开显示桥。
boot_stage() {   # $1 = 最后一个 boot_progress 事件名（可为空）→ 设 PCT / TXT
    case "$1" in
    boot_progress_enable_screen)   PCT=92; TXT="正在显示桌面" ;;
    boot_progress_ams_ready)       PCT=86; TXT="准备桌面" ;;
    boot_progress_pms_ready)       PCT=78; TXT="准备桌面" ;;
    boot_progress_pms_scan_end)    PCT=72; TXT="应用已就绪" ;;
    boot_progress_pms_data_scan_start) PCT=64; TXT="扫描已安装的应用" ;;
    boot_progress_pms_system_scan_start) PCT=60; TXT="扫描系统应用" ;;
    boot_progress_pms_start)       PCT=57; TXT="启动包管理" ;;
    boot_progress_system_run)      PCT=52; TXT="启动系统服务" ;;
    boot_progress_preload_end)     PCT=48; TXT="启动系统服务" ;;
    boot_progress_preload_start)   PCT=34; TXT="加载常用类库" ;;
    boot_progress_start)           PCT=28; TXT="启动 Android" ;;
    *)                             PCT=20; TXT="正在启动 Android 内核服务" ;;
    esac
}

# 开机画面上“已用时间”每 5 秒走一次；PackageManager 在优化（dexopt）应用时写出是第几个、哪个应用
# （logcat 里 PackageManager.DexOptimizer 的 "Running dexopt … pkg=…"；只在包管理阶段看，过滤到这一个标签，很便宜）
boot_tick() {
    type splash_tick >/dev/null 2>&1 || return 0
    if [ "${PCT:-0}" -ge 57 ] 2>/dev/null && [ "${PCT:-0}" -lt 86 ] 2>/dev/null; then
        dx=$($(vd_in) /system/bin/sh -c 'export PATH=/system/bin; logcat -d -s PackageManager.DexOptimizer 2>/dev/null' 2>/dev/null | grep "Running dexopt")
        if [ -n "$dx" ]; then
            dn=$(printf '%s\n' "$dx" | grep -c .); dp=$(printf '%s\n' "$dx" | tail -n 1 | sed -n 's/.* pkg=\([A-Za-z0-9._]*\).*/\1/p')
            echo "正在优化应用 第 $dn 个 · ${dp:-?}" > $W/splash.dexopt
        fi
    fi
    bw_draw splash_tick   # 只在画的时候拿锁：上面读 logcat 要好几秒，不能挡住“开机完成就放开显示”
}
# 开机完成的标记：容器的 init 在 sys.boot_completed=1 时往 /dev/kfb/ctl/booted（宿主的 $X/ctl/booted）写一个字。
# 宿主看这个文件不用起任何进程，boot_watch 等的时候每 0.25 秒看一眼，开机一完成就放开显示桥（以前每轮
# nsenter + logcat + getprop、再睡 2 秒，PW5 / PW6 模拟器上开机完成后桌面还要等 8–13 秒才出来）。
# 加在 init.kindle.rc 末尾自己的标记段里（和 slim.sh 的 vd-slim 段一样，不动原有内容）；老的系统盘不认也没关系：没有这个文件时照旧靠 getprop。
BM_B='# >>> vd-bootmark (generated by boot/lib/bootwatch.sh)'
BM_E='# <<< vd-bootmark'
boot_mark_setup() {
    rm -f $X/ctl/booted
    bm_f=$R/init.kindle.rc
    [ -f "$bm_f" ] || return 0
    grep -qF "$BM_B" "$bm_f" && return 0
    { cat "$bm_f"; echo "$BM_B"; echo "on property:sys.boot_completed=1"; echo "    write /dev/kfb/ctl/booted 1"; echo "$BM_E"; } > "$bm_f.vdbm" \
        && chmod 644 "$bm_f.vdbm" && mv -f "$bm_f.vdbm" "$bm_f" && t "boot watch: boot-completed marker added to init.kindle.rc"
    rm -f "$bm_f.vdbm"
    return 0
}
# 开机画面和“放开显示桥”互斥：画进度（fbink，模拟器上一次 1–2 秒）的时候不放开，放开以后不再画（splash_update 发现
# 画面已经撤了会整屏重画开机画面）。拿不到锁的那一笔进度就跳过，不等。
bw_draw() { mkdir $W/splash.lock 2>/dev/null || return 0; [ -f $W/bw.released ] || "$@"; rmdir $W/splash.lock 2>/dev/null; return 0; }
bw_release() {
    br_i=0; until mkdir $W/splash.lock 2>/dev/null || [ $br_i -ge 50 ]; do usleep 100000; br_i=$((br_i + 1)); done
    [ -f $W/bw.released ] || { touch $W/bw.released; splash_end; }
    rmdir $W/splash.lock 2>/dev/null; return 0
}
# 开机失败的记录（社区报告：第二次卡住时静默回到书库，屏幕上、USB 能看到的地方都没有原因）。
# veradroid/state/boot-fail.log 每次失败一行（电脑上 USB 打开就能看），boot-fail.count 是连续失败次数（开机成功清零，
# 以后做安全模式可以用）。bw_fail 最后进度% 轮数 最后的开机事件
BW_STATE=/mnt/base-us/veradroid/state
bw_fail() {
    mkdir -p $BW_STATE 2>/dev/null
    bf_n=$(cat $BW_STATE/boot-fail.count 2>/dev/null); case "$bf_n" in ''|*[!0-9]*) bf_n=0 ;; esac
    bf_n=$((bf_n + 1)); echo $bf_n > $BW_STATE/boot-fail.count 2>/dev/null
    [ "$(wc -l 2>/dev/null < $BW_STATE/boot-fail.log || echo 0)" -gt 200 ] && { tail -n 100 $BW_STATE/boot-fail.log > $BW_STATE/boot-fail.log.tmp 2>/dev/null && mv -f $BW_STATE/boot-fail.log.tmp $BW_STATE/boot-fail.log; }
    echo "$(date '+%Y-%m-%d %H:%M:%S') boot stalled at $1% after $2 checks (about 2.5 s each), last event ${3:-none}, failures in a row $bf_n; version $(cat $VD/version 2>/dev/null) model $(cat $VD/model 2>/dev/null) kernel $(uname -r)" >> $BW_STATE/boot-fail.log 2>/dev/null
    return 0
}
bw_ok() { rm -f $BW_STATE/boot-fail.count 2>/dev/null; return 0; }
boot_watch() {
    rm -f $W/splash.dexopt
    last=0; n=0; lastev=; forced=
    # TCG/older-PW5 boots are much slower than PW6 hardware; do not abort at 45 s.
    stall=${KFB_BOOT_TIMEOUT:-150}
    rm -f $W/bw.released; rmdir $W/splash.lock 2>/dev/null
    # 开机完成标记一出现就放开显示桥，不等下面这一轮（读 logcat、画进度、看 dexopt）做完：模拟器上一轮要好几秒，
    # 开机完成后桌面还要再等 5–11 秒（PW6 / PW5 模拟器）
    ( while [ ! -f $X/ctl/booted ]; do [ -n "$P" ] && kill -0 "$P" 2>/dev/null || exit 0; [ -f $W/bw.released ] && exit 0; usleep 250000; done
      bw_release ) </dev/null &
    bw_w=$!
    while [ $n -lt 180 ]; do
        n=$((n + 1))
        [ -n "$P" ] && kill -0 "$P" 2>/dev/null || break
        # tail / sed 在宿主这边做（和 legacy 一样）：系统镜像里的 toybox tail 不认 `tail -1`，原样输出全部行，
        # 以前 ev 永远是第一条事件（boot_progress_start）：进度条一直停在 28%（PW6 / PW5 模拟器日志 "boot watch: done ... last=28%"）
        # 进容器读开机进度（logcat）放到后台：模拟器 / 内存紧时它要好几秒，这期间也每 0.25 秒看一眼开机完成标记
        # （boot_mark_setup），标记一出现就不等它了。每轮至少 2.5 秒（以前是读完再睡 2 秒；卡住重试的轮数门槛不变）。
        rm -f $W/bw.out
        ( $(vd_in) /system/bin/sh -c 'export PATH=/system/bin; logcat -b events -d 2>/dev/null | grep boot_progress; echo "BC=$(getprop sys.boot_completed)"' > $W/bw.out 2>/dev/null ) </dev/null &
        bw_p=$!; k=0
        while [ ! -f $X/ctl/booted ]; do
            [ -n "$P" ] && kill -0 "$P" 2>/dev/null || break
            [ $k -ge 10 ] && ! kill -0 $bw_p 2>/dev/null && break
            [ $k -ge 80 ] && break
            usleep 250000; k=$((k + 1))
        done
        if [ -f $X/ctl/booted ]; then done_flag=1; ev=; kill $bw_p 2>/dev/null
        else
            kill $bw_p 2>/dev/null
            out=$(cat $W/bw.out 2>/dev/null)
            done_flag=$(echo "$out" | sed -n 's/^BC=//p' | tail -1)
            ev=$(echo "$out" | grep boot_progress | tail -1 | sed "s/.* I \(boot_progress[a-z_]*\).*/\1/")
        fi
        case "$ev" in boot_progress*) ;; *) ev= ;; esac
        # 开机完成：马上放开显示桥（整屏刷出桌面）。以前先画一格“100% 启动完成”再放开：那一帧马上被桌面盖掉，
        # 在 PW5 模拟器上却要多等一次 fbink 画图（约 1–2 秒）
        if [ "$done_flag" = 1 ]; then rm -f $W/boot.retry; bw_ok; bw_release; forced=done; break; fi
        boot_stage "$ev"
        # No boot_progress event yet: keep crawling, but never park at 27%
        # forever (the old clamp made a slow/quiet boot look frozen).
        [ -z "$ev" ] && { PCT=$((20 + n / 2)); [ $PCT -gt 45 ] && PCT=45; }
        [ "$PCT" -gt "$last" ] && { [ -n "$forced" ] || bw_draw splash_update $PCT "$TXT"; last=$PCT; }
        # A quiet/slow boot must not leave the splash stuck forever. If we
        # still have no boot_completed and no late events after 120s, release
        # the display bridge so the user can see Android or the error screen.
        # 放开画面后继续盯着：以前这里直接 break，下面“卡住就重试 / 回 Kindle”的分支永远走不到，
        # 开机失败的设备会停在暂停了 Kindle 界面的空白画面上，只能强制重启。
        if [ -z "$forced" ] && [ $n -ge 60 ] && [ $last -lt 60 ]; then
            bw_draw splash_update 90 "正在显示桌面"
            bw_release
            forced=1
            t "boot watch: forced splash end after ${n}s (last=$last%)"
        fi
        # 卡在 early boot（27% 左右）时自动回 Kindle 并重试一次；第二次仍失败就停在 Kindle，不再循环
        if [ $n -ge "$stall" ] && [ $last -lt 60 ]; then
            bw_fail "$last" "$n" "$ev"
            if [ -f $W/boot.retry ]; then
                t "boot stalled again at ${last}%: return to kindle"
                exec >>/tmp/veradroid-stop.log 2>&1; sh $VD/boot/stop.sh >/dev/null 2>&1
                # 两次都没起来、已经回到 Kindle：在书库上写清楚发生了什么、记录在哪（vd_notice 在后台补画约 15 秒）
                ( sleep 3; vd_notice "VeraDroid 没能启动：Android 开机两次都停在 ${last}% 左右，已回到 Kindle。再点一次可以重试；一直这样的话，请把 veradroid/state/boot-fail.log 发给我们" "VeraDroid did not start (boot stalled at ${last}% twice). Details: veradroid/state/boot-fail.log" ) </dev/null >>/tmp/veradroid-stop.log 2>&1 &
            else
                touch $W/boot.retry
                t "boot stalled at ${last}% after ${n}s: retry"
                ( exec >>/tmp/veradroid-stop.log 2>&1; VD_KEEP_RETRY=1 sh $VD/boot/stop.sh >/dev/null 2>&1; setsid sh $VD/boot/veradroid.sh home </dev/null >/tmp/vdretry.out 2>&1 & ) &
            fi
            kill $bw_w 2>/dev/null
            return
        fi
        [ -n "$forced" ] || [ -f $X/ctl/booted ] || boot_tick
    done
    rm -f $W/bw.out
    [ -n "$forced" ] || bw_release
    kill $bw_w 2>/dev/null
    t "boot watch: done after ${n}s (last=$last%)"
}
